import { SpeakerOption } from "../../application/studio/StudioRepository";
import { SpeakerDirectory } from "../../application/studio/SpeakerDirectory";
import { PortraitStore } from "../../application/studio/PortraitStore";
import { MEGGY_PORTRAIT_DATA_URL } from "../../assets/CanonicalMeggyPortrait";
import { MeggyPortraitSource } from "../../application/media/MeggyPortraitSource";

const SPEECH_SELECTOR = [
  '.callout[data-callout="joa-dialogue"]',
  '.callout[data-callout="joa-main-speech"]',
  '.callout[data-callout="joa-npc-speech"]',
  '.callout[data-callout="joa-vehicle-speech"]',
  '.callout[data-callout="joa-other-speech"]'
].join(", ");

/**
 * Resolves live character portrait references without copying art into notes.
 * Refreshes portraits when an identity-linked speaker is edited.
 */
export class LiveCalloutArtRenderer {
  private observer?: MutationObserver;
  private root?: Element;
  private refreshQueued = false;
  private generation = 0;
  private portraitCache = new Map<string, string | undefined>();

  constructor(
    private readonly studio: SpeakerDirectory,
    private readonly portraits: PortraitStore,
    private readonly meggyPortrait?: MeggyPortraitSource
  ) {}

  start(root: Element): void {
    this.root = root;
    this.refresh();
    if (typeof MutationObserver === "undefined") return;
    this.observer = new MutationObserver((changes) => {
      if (changes.some((change) => this.hasRelevantChange(change))) this.scheduleRefresh();
    });
    this.observer.observe(root, {childList: true, subtree: true, attributes: true, attributeFilter: ["data-callout-metadata", "data-callout"]});
  }

  /** Called by Obsidian's Reading-view Markdown postprocessor as well as Live Preview. */
  async hydrate(root: Element): Promise<void> {
    const callouts: HTMLElement[] = [];
    if (root.matches?.(SPEECH_SELECTOR)) callouts.push(root as HTMLElement);
    callouts.push(...Array.from(root.querySelectorAll<HTMLElement>(SPEECH_SELECTOR)));
    if (!callouts.length) return;

    const generation = this.generation;
    const speakers = await this.studio.listSpeakers();
    const byId = new Map(speakers.map((speaker) => [speaker.id, speaker]));
    const byName = new Map<string, SpeakerOption | undefined>();
    for (const speaker of speakers) {
      const key = speaker.name.normalize("NFC").trim();
      // Avoid guessing identity when two characters share one name.
      byName.set(key, byName.has(key) ? undefined : speaker);
    }

    for (const node of callouts) {
      if (generation !== this.generation) continue;
      const metadata = node.getAttribute("data-callout-metadata") ?? "";
      const tokens = metadata.trim().split(/\s+/).filter(Boolean);
      const speakerToken = tokens.find((t) => /^joa-speaker-[\w-]+$/.test(t));
      const speakerId = speakerToken?.slice("joa-speaker-".length);
      const titleInner = node.querySelector<HTMLElement>(".callout-title-inner");
      const fallbackName = (titleInner?.textContent ?? "").normalize("NFC").trim();
      const speaker = speakerId && speakerId !== "meggy"
        ? byId.get(speakerId)
        : (!speakerId && fallbackName ? byName.get(fallbackName) : undefined);
      const isMeggy = speakerId === "meggy" || (!speakerId && node.dataset.callout === "joa-dialogue" && fallbackName === "Meggy");
      await this.updatePortrait(node, speaker, isMeggy);
    }
  }

  refresh(): void {
    this.generation++;
    this.portraitCache.clear();
    this.scheduleRefresh();
  }

  dispose(): void {
    this.observer?.disconnect();
    this.observer = undefined;
    this.root = undefined;
  }

  private scheduleRefresh(): void {
    if (this.refreshQueued) return;
    this.refreshQueued = true;
    // Batch multiple DOM mutations generated by Obsidian's editor in one tick.
    setTimeout(() => {
      this.refreshQueued = false;
      if (this.root) void this.hydrate(this.root).catch(() => undefined);
    }, 60);
  }

  private hasRelevantChange(change: MutationRecord): boolean {
    if (change.type === "attributes") return true;
    for (const n of Array.from(change.addedNodes)) {
      if (n.nodeType !== 1) continue;
      const el = n as Element;
      if (el.matches?.(SPEECH_SELECTOR) || el.querySelector?.(SPEECH_SELECTOR)) return true;
    }
    return false;
  }

  private async updatePortrait(node: HTMLElement, speaker?: SpeakerOption, isMeggy = false): Promise<void> {
    const title = node.querySelector<HTMLElement>(".callout-title");
    if (!title) return;
    const oldImage = title.querySelector<HTMLImageElement>(".joa-live-portrait");
    let src: string | undefined;
    if (isMeggy) {
      // The canonical Meggy artwork cannot be replaced by custom portrait files.
      src = await (this.meggyPortrait?.getDataUrl() ?? Promise.resolve(MEGGY_PORTRAIT_DATA_URL));
    } else if (speaker?.portraitPath) {
      // All other speakers still resolve their latest image on refresh.
      const path = speaker.portraitPath;
      let portrait = this.portraitCache.get(path);
      if (!this.portraitCache.has(path)) {
        portrait = await this.portraits.getDataUrl(path).catch(() => undefined);
        this.portraitCache.set(path, portrait);
      }
      src = portrait;
    }
    if (!src) { oldImage?.remove(); node.classList.remove("joa-has-portrait"); return; }
    const img = oldImage ?? document.createElement("img");
    img.className = "joa-live-portrait";
    img.alt = speaker?.name ? `${speaker.name} portresi` : "Meggy portresi";
    if (img.src !== src) img.src = src;
    if (!oldImage) title.insertBefore(img, title.firstChild);
    node.classList.add("joa-has-portrait");
  }

}
